"""Write reports/RESULTS.md from the CSV outputs, so every number in it comes from a file in reports/."""
from __future__ import annotations

import json

import pandas as pd

from . import config


def md_table(df: pd.DataFrame, digits: int = 3) -> str:
    """Markdown table without extra dependencies."""
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.{digits}f}"
        return str(v)
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    rule = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def build() -> str:
    r = config.REPORTS_DIR
    quality = pd.read_csv(r / "data_quality.csv")
    xg = pd.read_csv(r / "xg_metrics.csv")
    selected = json.loads((r / "xg_selected_model.json").read_text())["selected"]
    fin = pd.read_csv(r / "finishing_model.csv").iloc[0]
    fin_val = pd.read_csv(r / "finishing_validation.csv")
    fin_top = pd.read_csv(r / "finishing_highest_volume_shooters.csv")
    traj = pd.read_csv(r / "trajectories_mixed_models.csv")
    rel = pd.read_csv(r / "reliability_minutes.csv")
    target = config.RELIABILITY_TARGET

    rel_wide = (rel.pivot(index="label", columns="position_group", values=f"minutes_for_{target}")
                [list(config.POSITION_GROUPS)].round(0).astype(int).reset_index()
                .rename(columns={"label": "Metric (per 90)"}))
    rel_wide = rel_wide.set_index("Metric (per 90)").loc[list(config.RATE_METRICS.values())].reset_index()
    traj_view = traj.assign(
        change=lambda d: d.change_per_year.map("{:+.3f}".format) + " (" + d.change_per_year_low.map("{:.3f}".format)
        + " to " + d.change_per_year_high.map("{:.3f}".format) + ")",
    )[["label", "mean_per90", "change", "icc", "slope_sd", "slope_lr_p_value"]].rename(columns={
        "label": "Metric (per 90)", "mean_per90": "Mean", "change": "Change per year (95% CI)",
        "icc": "ICC (player share)", "slope_sd": "SD of player slopes", "slope_lr_p_value": "p (slopes differ)"})

    lines = [
        "# Results",
        "",
        "Generated by `python -m player_development analyse` from the CSV files in this folder. "
        "Data: StatsBomb open data, FA Women's Super League 2018/19, 2019/20, 2020/21 and 2023/24.",
        "",
        "## 1. Data quality",
        "",
        md_table(quality),
        "",
        "## 2. Expected goals (xG)",
        "",
        f"Selected model: **{selected.replace('_', ' ')}** (lowest cross-validated log loss). "
        "Folds are grouped by match so shots from the same game never sit in both training and test data. "
        "The 2023/24 season was used once, at the end.",
        "",
        md_table(xg[["model", "evaluation", "shots", "goals", "xg_total", "log_loss", "brier", "roc_auc",
                     "calibration_error"]]),
        "",
        "![xG calibration](figures/xg_calibration.png)",
        "![xG permutation importance](figures/xg_importance.png)",
        "",
        "## 3. Finishing skill (hierarchical Gamma-Poisson model)",
        "",
        f"League-average finishing multiplier mu = {fin.mu:.3f}. Best-estimate spread of finishing skill between "
        f"players: SD {fin.between_player_sd:.3f}; the largest spread the data cannot rule out (95% profile "
        f"likelihood): SD {fin.between_player_sd_95_upper:.3f}.",
        "",
        f"Season-to-season correlation of raw finishing (goals minus xG per shot, players with "
        f"{int(fin.repeatability_min_shots_each_season)}+ shots in both seasons, n = "
        f"{int(fin.repeatability_player_season_pairs)}): r = {fin.repeatability_pearson_r:.2f} "
        f"(p = {fin.repeatability_p_value:.2f}).",
        "",
        "Predicting next season's goals from next season's xG and this season's finishing:",
        "",
        md_table(fin_val),
        "",
        "Highest-volume shooters (all four seasons). `low`/`high` is the 80% interval; `_wide` columns use the "
        "largest plausible skill spread:",
        "",
        md_table(fin_top, 2),
        "",
        "![Finishing shrinkage](figures/finishing_shrinkage.png)",
        "",
        "## 4. Development trajectories (longitudinal mixed-effects models)",
        "",
        f"Outfield player-seasons with {config.MIN_MINUTES}+ minutes: {int(traj.player_seasons.iloc[0])} rows, "
        f"{int(traj.players.iloc[0])} players, {int(traj.players_2plus_seasons.iloc[0])} with two or more seasons. "
        "Model: rate ~ years + position + (1 + years | player), REML.",
        "",
        md_table(traj_view),
        "",
        "![Trajectories](figures/trajectories.png)",
        "",
        "## 5. Minutes needed before a metric is reliable",
        "",
        f"Minutes of play needed for a split-half reliability of {target} (200 random splits, within position group):",
        "",
        md_table(rel_wide, 0),
        "",
        "![Reliability](figures/reliability_minutes.png)",
        "",
        "## 6. Example profiles",
        "",
        "Percentiles within position group for the 2023/24 season, with metrics below the reliability threshold "
        "greyed out. Players: the highest-minute defender, midfielder and forward of Manchester City WFC.",
        "",
        "![Profiles](figures/profiles_examples.png)",
        "",
    ]
    text = "\n".join(lines)
    (r / "RESULTS.md").write_text(text, encoding="utf-8")
    return text
